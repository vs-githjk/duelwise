/*
  Design token pipeline. Converts a token file into apps/web/src/styles/tokens.css.

  Input: plan/design/tokens.json when it exists (a partial or full override), else apps/web/src/styles/tokens.default.json.
  An override is merged over the defaults key by key, so a missing key falls back to the default value.
  Output: light variables on :root, the dark set under the OS query and under data-theme="dark", theme independent
  scales and stage (HUD) tokens, and the Tailwind v4 @theme block (a colour utility for every colour token).

  Usage: bun run design:tokens            write tokens.css
         bun run design:tokens -- --check exit 1 if tokens.css is not what the pipeline would write
*/
import { existsSync, readFileSync, writeFileSync } from 'node:fs'

export type Flat = Record<string, string>
export type Grouped = Record<string, Flat>
export interface Tokens {
  version?: number
  fonts: Flat
  light: Grouped
  dark: Flat
  scales: Grouped
  theme: Flat
  hud: Flat
}

const repoRoot = new URL('../../', import.meta.url).pathname
const defaultsPath = `${repoRoot}apps/web/src/styles/tokens.default.json`
const outputPath = `${repoRoot}apps/web/src/styles/tokens.css`

const NAME = /^[a-z0-9][a-z0-9-]*$/
const COLOUR = /^(#[0-9a-fA-F]{3,8}|(rgb|rgba|hsl|hsla|oklch|oklab)\([^;{}]*\))$/
const IGNORED_KEYS = new Set(['version', 'meta', 'name', 'direction'])
const SECTIONS = ['fonts', 'light', 'dark', 'scales', 'theme', 'hud'] as const

export function loadDefaults(): Tokens {
  return JSON.parse(readFileSync(defaultsPath, 'utf8')) as Tokens
}

export function resolveInputPath(root: string = repoRoot): string {
  const designed = `${root}plan/design/tokens.json`
  return existsSync(designed) ? designed : `${root}apps/web/src/styles/tokens.default.json`
}

function isObject(v: unknown): v is Record<string, unknown> {
  return typeof v === 'object' && v !== null && !Array.isArray(v)
}

function checkEntry(name: string, value: unknown): string {
  if (!NAME.test(name)) throw new Error(`token name "${name}" must be lowercase letters, digits and hyphens`)
  if (typeof value !== 'string' || value.trim() === '' || /[;{}\n\r]|\/\*|\*\//.test(value)) {
    throw new Error(`token value for "${name}" must be a plain CSS value string without ; { } or comments`)
  }
  return value.trim()
}

function mergeFlat(base: Flat, over: unknown, section: string): Flat {
  if (over === undefined) return { ...base }
  if (!isObject(over)) throw new Error(`section "${section}" must be an object`)
  const out = { ...base }
  for (const [k, v] of Object.entries(over)) out[k] = checkEntry(k, v)
  return out
}

function mergeGrouped(base: Grouped, over: unknown, section: string): Grouped {
  if (over === undefined) return Object.fromEntries(Object.entries(base).map(([g, f]) => [g, { ...f }]))
  if (!isObject(over)) throw new Error(`section "${section}" must be an object`)
  const out: Grouped = Object.fromEntries(Object.entries(base).map(([g, f]) => [g, { ...f }]))
  for (const [g, flat] of Object.entries(over)) {
    if (/\*\//.test(g) || /[\n\r]/.test(g)) throw new Error(`group name "${g}" is not allowed`)
    out[g] = mergeFlat(out[g] ?? {}, flat, `${section}.${g}`)
  }
  return out
}

export function mergeTokens(base: Tokens, over: unknown): Tokens {
  if (!isObject(over)) throw new Error('a token file must be an object')
  for (const k of Object.keys(over)) {
    if (!(SECTIONS as readonly string[]).includes(k) && !IGNORED_KEYS.has(k)) throw new Error(`unknown token section "${k}"`)
  }
  return {
    version: base.version,
    fonts: mergeFlat(base.fonts, over.fonts, 'fonts'),
    light: mergeGrouped(base.light, over.light, 'light'),
    dark: mergeFlat(base.dark, over.dark, 'dark'),
    scales: mergeGrouped(base.scales, over.scales, 'scales'),
    theme: mergeFlat(base.theme, over.theme, 'theme'),
    hud: mergeFlat(base.hud, over.hud, 'hud'),
  }
}

const decl = (flat: Flat, indent: string) => Object.entries(flat).map(([k, v]) => `${indent}--${k}: ${v};`)

function groupedLines(g: Grouped, indent: string): string[] {
  const lines: string[] = []
  for (const [name, flat] of Object.entries(g)) {
    if (lines.length) lines.push('')
    lines.push(`${indent}/* ${name} */`, ...decl(flat, indent))
  }
  return lines
}

export function buildCss(overrides: unknown = {}, defaults: Tokens = loadDefaults()): string {
  const t = mergeTokens(defaults, overrides)
  const lightFlat: Flat = Object.assign({}, ...Object.values(t.light))
  const colourNames = Object.entries(lightFlat).filter(([, v]) => COLOUR.test(v)).map(([k]) => k)
  const out: string[] = [
    '/*',
    '  GENERATED by scripts/design/tokens-to-css.ts (bun run design:tokens). Do not edit by hand.',
    '  Source: plan/design/tokens.json when it exists, else tokens.default.json in this folder.',
    '  Every colour, radius, spacing, type and motion value is a CSS variable here, so the chosen design swaps in one place.',
    '  Components use the Tailwind utilities mapped below (bg-canvas, text-ink, rounded-card ...), never literals.',
    '  Theme: one light Sunroom palette on every page, whatever the OS dark-mode setting is (no dark set is emitted).',
    '*/',
    '',
    ':root {',
    '  color-scheme: light;',
    '',
    ...groupedLines(t.light, '  '),
    '}',
    '',
    '/* spacing, type and motion scales (the design system\'s fixed scale, not fluid) */',
    ':root {',
    ...groupedLines(t.scales, '  '),
    '}',
    '',
    '/* stage tokens for the real-time games: a night scene, so they do not change with the site theme */',
    ':root {',
    ...decl(t.hud, '  '),
    '}',
    '',
    '/* Tailwind v4 theme: utilities like bg-canvas, text-ink, border-line, bg-action, text-action-ink, font-display, rounded-card */',
    '@theme inline {',
    ...Object.entries(t.fonts).map(([k, v]) => `  --font-${k}: ${v};`),
    '',
    ...colourNames.map((k) => `  --color-${k}: var(--${k});`),
    '',
    ...Object.entries(t.theme).map(([k, v]) => `  --${k}: var(--${v});`),
    '}',
    '',
  ]
  return out.join('\n')
}

if (import.meta.main) {
  const check = process.argv.includes('--check')
  const input = resolveInputPath()
  const raw = JSON.parse(readFileSync(input, 'utf8'))
  const css = buildCss(input === defaultsPath ? {} : raw)
  const source = input.startsWith(repoRoot) ? input.slice(repoRoot.length) : input
  if (check) {
    const current = existsSync(outputPath) ? readFileSync(outputPath, 'utf8') : ''
    if (current !== css) {
      console.error(`tokens.css is out of date with ${source}; run: bun run design:tokens`)
      process.exit(1)
    }
    console.log(`tokens.css is up to date (${source})`)
  } else {
    writeFileSync(outputPath, css)
    console.log(`wrote ${outputPath} from ${source}`)
  }
}
